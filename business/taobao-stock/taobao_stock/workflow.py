"""Reusable, snapshot-bound jobs for the one-click launcher.

Every new job gets its own immutable Excel copy and execution ledger.  Resume
uses that same ledger; starting another job deliberately scans the new input
again, without permanently excluding historical pilot IDs.
"""
import asyncio
from contextlib import asynccontextmanager
from copy import deepcopy
from datetime import datetime, timedelta, timezone
import hashlib
import json
from pathlib import Path
import shutil
from uuid import uuid4

from .batch import BatchAdapter
from .engine import execute_run
from .errors import SessionError, ShopMismatch, UnsupportedItem
from .excel import WorkbookError, load_workbook_targets, normalize_title
from .matching import match_item
from .report import write_reports
from .session import browser_session, load_shop_binding, run_lock, save_shop_binding
from .state import atomic_json, utc_now
from .summary_report import write_summary

WORKFLOW_VERSION = 1
EXPECTED_SHOP = {'name': '中古Remake商店', 'shop_id': '227180723'}
FINISHED = {'completed', 'completed_with_exceptions'}
BEIJING = timezone(timedelta(hours=8))


class WorkflowError(ValueError):
    """Safe, user-facing validation errors generated by this module."""


def _hash(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def _read(path):
    with Path(path).open(encoding='utf-8') as stream:
        value = json.load(stream)
    if not isinstance(value, dict):
        raise WorkflowError('任务记录格式无效，不能继续执行。')
    return value


def _safe_error(error):
    if isinstance(error, (WorkflowError, WorkbookError, SessionError, UnsupportedItem)):
        return str(error)
    if isinstance(error, (OSError, IOError)):
        return '文件或浏览器环境无法访问（%s），请检查文件位置和运行环境。' % type(error).__name__
    return '任务未完成（%s）。进度与报告已保存，请检查运行环境后再处理。' % type(error).__name__


def _public(run, run_dir):
    result = deepcopy(run)
    directory = Path(run_dir).resolve()
    result['run_dir'] = str(directory)
    report_dir = directory / 'diagnostics' / 'record-error' if result.get('state_corrupt') else directory
    result['report_path'] = str(report_dir / '简洁报告.html')
    has_writes = any(
        i.get('touched') or i.get('write_pending') or i.get('inventory_attempts')
        or i.get('inventory_verified_at') or i.get('relisting_started_at')
        or i.get('relisting_verified_at') or i.get('result') in {'listed', 'zero_stock'}
        for i in result.get('items', [])
    )
    if result.get('state_corrupt') and ((directory / 'state.json').exists() or (directory / 'events.jsonl').exists()):
        has_writes = True  # Possible writes cannot be ruled out from a damaged ledger.
    result['has_writes'] = bool(has_writes)
    result['requires_manual_review'] = bool(
        result.get('state_corrupt') or
        (result.get('status') == 'failed' and has_writes) or
        any(i.get('needs_manual_check') and i.get('result') not in {'listed', 'zero_stock'}
            for i in result.get('items', []))
    )
    result['resumable'] = bool(result.get('source_validated') and result.get('status') not in FINISHED | {'failed'})
    return result


def _reports(run_dir, run):
    directory = Path(run_dir) / 'diagnostics' / 'record-error' if run.get('state_corrupt') else Path(run_dir)
    write_reports(directory, run)
    write_summary(directory, run)


def _damaged_record(run_dir, manifest=None):
    """Diagnostic metadata only: never treat a surviving fragment as a plan."""
    manifest = manifest if isinstance(manifest, dict) else {}
    try:
        state = _read(run_dir / 'state.json')
    except (OSError, ValueError, TypeError):
        state = {}
    keys = ('job_id', 'created_at', 'source_path', 'source_filename', 'source_validated',
            'source_sha256', 'rules_version', 'product_count', 'sku_count', 'shop')
    metadata = {key: state.get(key, manifest.get(key)) for key in keys}
    # A surviving state can identify the original input, but cannot authorize
    # execution without its manifest. Snapshot hashing is a last resort for
    # matching the damaged record to a newly selected copy of the same file.
    hashes = []
    for candidate in (state.get('source_sha256'), manifest.get('source_sha256')):
        if isinstance(candidate, str) and len(candidate) == 64 and all(c in '0123456789abcdefABCDEF' for c in candidate):
            hashes.append(candidate.lower())
    try:
        if (run_dir / 'source.xlsx').is_file():
            hashes.append(_hash(run_dir / 'source.xlsx'))
    except OSError:
        pass
    hashes = list(dict.fromkeys(hashes))
    metadata['source_sha256'] = hashes[0] if hashes else None
    metadata['source_hash_candidates'] = hashes
    metadata['source_identity_unknown'] = not bool(hashes)
    metadata.update(workflow_version=WORKFLOW_VERSION, status='failed', phase='record_error',
                    workflow_stage='record_error', state_corrupt=True, resumable=False, items=[],
                    job_error='任务记录缺失、损坏或身份不符，无法确认先前修改结果。原审计文件已保留；请人工核查，不能自动重新同步。')
    metadata['pause_reason'] = metadata['job_error']
    return metadata


def _persist_preview(run_dir, run):
    run['updated_at'] = utc_now()
    atomic_json(Path(run_dir) / 'preview-progress.json', run)
    _reports(run_dir, run)


def _manifest(run):
    keys = ('workflow_version', 'job_id', 'created_at', 'source_path', 'source_filename',
            'source_sha256', 'rules_version', 'source_validated', 'product_count', 'sku_count',
            'shop', 'phase', 'workflow_stage', 'status', 'pause_reason', 'job_error')
    return {key: deepcopy(run[key]) for key in keys if key in run}


def create_job(root, excel):
    """Create a new local task, including a failure report for invalid input.

    A valid job is merely prepared here.  No browser is opened and no request
    is sent.  The caller explicitly starts it with ``run_job``.
    """
    root = Path(root).expanduser().resolve()
    original = Path(excel).expanduser().resolve()
    stamp = datetime.now(BEIJING).strftime('%Y%m%d_%H%M%S')
    job_id = stamp + '_' + uuid4().hex[:8]
    run_dir = root / 'output' / 'jobs' / job_id
    run_dir.mkdir(parents=True, exist_ok=False, mode=0o700)
    run = dict(workflow_version=WORKFLOW_VERSION, job_id=job_id,
               created_at=datetime.now(timezone.utc).isoformat(timespec='microseconds'),
               source_path=str(original), source_filename=original.name, source_validated=False,
               shop=dict(EXPECTED_SHOP), phase='input', workflow_stage='input', status='preview',
               items=[], products=[], previous_completed=[], unmatched_products=[], warnings=[])
    try:
        if not original.is_file() or original.suffix.lower() != '.xlsx':
            raise WorkflowError('请选择存在的 .xlsx 库存文件。')
        before = _hash(original)
        snapshot = run_dir / 'source.xlsx'
        shutil.copyfile(original, snapshot)
        snapshot.chmod(0o600)
        if _hash(original) != before or _hash(snapshot) != before:
            raise WorkflowError('复制期间 Excel 发生变化，请关闭编辑后重新选择文件。')
        source = load_workbook_targets(snapshot)
        if source['source_sha256'] != before:
            raise WorkflowError('库存副本指纹校验失败，未启动任务。')
        run.update(source)
        run.update(source_path=str(original), source_filename=original.name, source_snapshot='source.xlsx',
                   source_validated=True, phase='previewing', workflow_stage='discovery', status='preview',
                   lookup_items=[], lookup_completed=[], previous_completed=[],
                   pilot_item_id='validated-api-workflow', pilot_verified=True,
                   authorization='用户选择本次 Excel 并启动库存同步；范围为此文件匹配的二店商品链接')
    except KeyboardInterrupt:
        run.update(status='failed', phase='input_error', workflow_stage='input',
                   job_error='已取消读取输入文件，未修改店铺；请重新选择文件。',
                   pause_reason='已取消读取输入文件，未修改店铺；请重新选择文件。')
    except Exception as error:
        run.update(status='failed', phase='input_error', workflow_stage='input',
                   job_error=_safe_error(error), pause_reason=_safe_error(error))
    atomic_json(run_dir / 'job.json', _manifest(run))
    _persist_preview(run_dir, run)
    return run_dir


def load_job(run_dir):
    """Read authoritative execution state before any preview checkpoint."""
    run_dir = Path(run_dir).expanduser().resolve()
    manifest = None
    try:
        manifest = _read(run_dir / 'job.json')
        if manifest.get('workflow_version') != WORKFLOW_VERSION:
            raise WorkflowError('该目录不是当前版本创建的可复用任务。')
    except (OSError, ValueError, TypeError):
        if (run_dir / 'state.json').exists() or (run_dir / 'events.jsonl').exists():
            return _public(_damaged_record(run_dir, manifest), run_dir)
        raise WorkflowError('该目录不是当前版本创建的可复用任务。') from None
    path = run_dir / ('state.json' if (run_dir / 'state.json').exists() else 'preview-progress.json')
    try:
        if not (run_dir / 'state.json').exists() and (run_dir / 'events.jsonl').exists():
            raise WorkflowError('执行记录缺失但执行日志仍在，不能回退到旧预览。')
        run = _read(path)
        if run.get('workflow_version') != WORKFLOW_VERSION or run.get('job_id') != manifest.get('job_id'):
            raise WorkflowError('任务身份与执行记录不一致，不能恢复。')
        if any(run.get(key) != manifest.get(key) for key in ('source_sha256', 'rules_version', 'shop')):
            raise WorkflowError('执行记录的输入指纹、规则或店铺与原任务不一致。')
        run['created_at'] = manifest['created_at']
    except (OSError, ValueError, TypeError):
        # Never silently fall back to an older preview after a damaged execution
        # ledger: it might replay inventory that was already committed.
        run = _damaged_record(run_dir, manifest)
    return _public(run, run_dir)


def find_jobs(root):
    result = []
    folder = Path(root).expanduser().resolve() / 'output' / 'jobs'
    if not folder.exists():
        return result
    for path in folder.iterdir():
        if not path.is_dir() or not any((path / name).is_file() for name in ('job.json', 'state.json', 'events.jsonl')):
            continue
        try:
            run = load_job(path)
        except (OSError, ValueError, TypeError):
            continue
        if run.get('state_corrupt'):
            _reports(path, run)
        keys = ('run_dir', 'status', 'phase', 'workflow_stage', 'source_sha256', 'source_path',
                'source_filename', 'created_at', 'report_path', 'resumable', 'job_error', 'pause_reason',
                'state_corrupt', 'has_writes', 'requires_manual_review', 'source_hash_candidates',
                'source_identity_unknown')
        result.append({key: run.get(key) for key in keys})
    return sorted(result, key=lambda job: (job.get('created_at') or '', job['run_dir']), reverse=True)


def _notify(callback, event, run, **extra):
    if callback is None:
        return
    info = dict(run_dir=run.get('run_dir'), status=run.get('status'), phase=run.get('workflow_stage'), **extra)
    try:
        callback(event, info)
    except Exception:
        # A display callback must not interrupt an in-flight inventory commit.
        pass


def _validate_source(run_dir, run):
    if run.get('shop') != EXPECTED_SHOP:
        raise WorkflowError('任务店铺身份不符，未执行任何新操作。')
    source = load_workbook_targets(Path(run_dir) / 'source.xlsx')
    if source['source_sha256'] != run.get('source_sha256'):
        raise WorkflowError('任务库存副本已变化，不能恢复原执行计划。')
    if source.get('rules_version') != run.get('rules_version'):
        raise WorkflowError('库存读取规则已更新，请重新选择文件创建新任务。')
    if source['products'] != run.get('products'):
        raise WorkflowError('任务库存目标与固定副本不一致，已停止。')
    return source


@asynccontextmanager
async def _adapter_context(root, adapter):
    binding = load_shop_binding(root)
    if binding is not None and binding != EXPECTED_SHOP:
        raise ShopMismatch('已绑定店铺不是目标二店，不能自动换绑。')
    if adapter is not None:
        yield adapter
        return
    async with browser_session(root) as page:
        owned = BatchAdapter(page, binding or EXPECTED_SHOP, request_interval=3)
        try:
            yield owned
        finally:
            # This adapter lazily creates its own inventory tab. Retain the
            # main shop tab/Chrome/login profile, but don't accumulate a new
            # inventory tab after every reusable job.
            inventory_page = owned.inventory_page
            if inventory_page is not None:
                try:
                    if not inventory_page.is_closed():
                        await inventory_page.close()
                except Exception:
                    pass


def _set_scope(adapter, run):
    items = run.get('items', [])
    ids = [str(i.get('item_id') or '') for i in items]
    if any(not i for i in ids) or len(ids) != len(set(ids)):
        raise WorkflowError('预览商品 ID 缺失或重复，不能提交。')
    eligible = [i for i in items if i.get('eligible')]
    adapter.write_scope = frozenset(str(i['item_id']) for i in eligible)
    adapter.sku_write_scope = frozenset(str(s['sku_id']) for i in eligible for s in i['skus'])


async def _process(root, run_dir, run, source, adapter, callback):
    adapter.write_scope = frozenset()
    adapter.sku_write_scope = frozenset()
    shop = await adapter.verify_shop()
    if shop != EXPECTED_SHOP:
        raise ShopMismatch('当前店铺名称或 ID 不符，已停止。')
    save_shop_binding(root, shop)
    run.pop('pause_reason', None)
    run.pop('job_error', None)
    if not (run_dir / 'state.json').exists():
        if run.get('phase') != 'preview_ready':
            run.update(status='preview', phase='previewing', workflow_stage='discovery')
            def save():
                _persist_preview(run_dir, run)
                _notify(callback, 'progress', run, looked_up=len(run.get('lookup_completed', [])),
                        product_count=run['product_count'], candidates=len(run.get('lookup_items', [])),
                        details=len(run['items']))
            save()
            listing = await adapter.discover(source, run, save)
            by_title = {p['normalized_title']: p for p in source['products']}
            seen = {normalize_title(i['title']) for i in listing}
            run['unmatched_products'] = [p['title'] for p in source['products'] if p['normalized_title'] not in seen]
            done = {i['item_id'] for i in run['items']}
            run['workflow_stage'] = 'details'
            for index, item in enumerate(listing, 1):
                if item['item_id'] in done:
                    continue
                product = by_title.get(normalize_title(item['title']))
                if product is None:
                    raise WorkflowError('查询结果中包含范围外标题，未执行。')
                _notify(callback, 'progress', run, index=index, total=len(listing), item_id=item['item_id'])
                try:
                    raw = await adapter.read_item(item['item_id'], known_item=item)
                    result = match_item(product, raw)
                except SessionError:
                    raise
                except Exception as error:
                    result = dict(item, eligible=False, reason='读取未通过：' + _safe_error(error),
                                  skus=[], source_title=product['title'])
                run['items'].append(result)
                done.add(item['item_id'])
                save()
            run.update(phase='preview_ready', workflow_stage='execution')
            save()
            atomic_json(run_dir / 'preview.json', run)
    if run.get('phase') != 'preview_ready':
        raise WorkflowError('任务没有完整预览，不能执行。')
    _set_scope(adapter, run)
    run['workflow_stage'] = 'execution'
    _notify(callback, 'execution_started', run, candidate_count=len(run['items']))
    return await execute_run(adapter, run, run_dir, resume=(run_dir / 'state.json').exists(),
                             skip_global_preflight=True, coalesce_relist_read=True)


async def run_job(root, run_dir, *, adapter=None, on_event=None):
    """Run/resume a job and always return its latest report-bearing record.

    ``adapter`` is injectable for offline tests. This module never starts a
    second run while the shared browser lock is held elsewhere. Completed jobs
    return their existing result without opening Chrome or resynchronizing sales.
    """
    root = Path(root).expanduser().resolve()
    run_dir = Path(run_dir).expanduser().resolve()
    run = load_job(run_dir)
    if run.get('status') in FINISHED | {'failed'}:
        _reports(run_dir, run)
        return _public(run, run_dir)
    error_status = error_message = None
    locked = False
    lock = run_lock(root)
    try:
        lock.__enter__()
        locked = True
        # A competing run may have finished while this caller was opening.
        run = load_job(run_dir)
        if run.get('status') in FINISHED | {'failed'}:
            return _public(run, run_dir)
        source = _validate_source(run_dir, run)
        async with _adapter_context(root, adapter) as current:
            run = await _process(root, run_dir, run, source, current, on_event)
    except (asyncio.CancelledError, KeyboardInterrupt):
        error_status, error_message = 'interrupted', '任务已中断，执行进度已保存；下次选择继续，先回读实际状态，不重复扣减。'
    except SessionError as error:
        error_status, error_message = 'paused', _safe_error(error)
    except Exception as error:
        error_status = 'failed' if isinstance(error, (WorkflowError, WorkbookError)) else (
            'paused' if (run_dir / 'state.json').exists() else 'failed')
        error_message = _safe_error(error)
    finally:
        try:
            # The engine may have persisted a successful/partial write just
            # before raising. Never replace it with a stale preview object.
            if locked and (run_dir / 'state.json').exists():
                run = load_job(run_dir)
            if error_status is not None:
                run.update(status=error_status, pause_reason=error_message, job_error=error_message)
            run['updated_at'] = utc_now()
            if locked:
                if (run_dir / 'state.json').exists() and not run.get('state_corrupt'):
                    atomic_json(run_dir / 'state.json', run)
                elif not run.get('state_corrupt'):
                    atomic_json(run_dir / 'preview-progress.json', run)
                _reports(run_dir, run)
            else:
                # Never overwrite the active task's ledger/report when another
                # invocation owns the browser lock. Its current report exists.
                run['lock_busy'] = True
            _notify(on_event, 'finished', run, report_path=str(run_dir / '简洁报告.html'))
        finally:
            if locked:
                lock.__exit__(None, None, None)
    return _public(run, run_dir)
